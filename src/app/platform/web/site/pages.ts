export const ICONS = { svg: "icon.svg", png32: "icon-32.png", png256: "icon-256.png", png512: "icon-512.png" } as const;

export const esc = (s: string): string =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

const trimSlash = (u: string) => u.replace(/\/+$/, "");
export const absUrl = (siteUrl: string, path: string): string => `${trimSlash(siteUrl)}${path}`;

// ── CSP ──
// 근거(데브로그 11-15 (04)): 데스크톱 tauri.conf.json 의 하드닝 CSP 를 웹으로 옮기되 두 곳만 연다.
//   img-src https: — README 의 배지·스크린샷은 출처가 제각각(shields.io·user-images·CI 배지…)이라 허용 목록으로는
//     README 미리보기가 깨진다. 이미지는 수동 콘텐츠이고 미리보기 iframe 은 스크립트 없는 샌드박스 + DOMPurify.
//     http: 는 열지 않는다(혼합 콘텐츠).
//   connect-src https: — ?url= 로 여는 원본이 사용자가 고른 임의 HTTPS(CORS 허용) 주소라서. 스크립트는 'self' 뿐이라
//     이 통로로 코드를 들여올 수 없다.
// 'unsafe-inline' 스타일은 데스크톱과 같은 이유(에디터·mermaid·KaTeX 가 인라인 스타일을 쓴다). 스크립트는 인라인 금지.
export function buildCsp(extraConnect: string[] = []): string {
  return [
    "default-src 'self'",
    "script-src 'self'",
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob: https:",
    "font-src 'self' data:",
    `connect-src ${["'self'", "https:", ...extraConnect].join(" ")}`,
    "worker-src 'self' blob:",
    "frame-src 'self'",
    "manifest-src 'self'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join("; ");
}

export function headersFile(base = "/"): string {
  const b = normBase(base);
  const noCache = [b, `${b}index.html`, `${b}404.html`, `${b}sw.js`, `${b}*.webmanifest`, ...LANGS.flatMap((l) => [`${b}${l}/`, `${b}${l}/*`])];
  return [
    "# generated by vite.config.ts (web) from app/platform/web/site/pages.ts - do not edit",
    "/*",
    "  X-Content-Type-Options: nosniff",
    "  Referrer-Policy: strict-origin-when-cross-origin",
    "  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()",
    `  Content-Security-Policy: ${buildCsp()}`,
    "",
    `${b}assets/*`,
    "  Cache-Control: public, max-age=31536000, immutable",
    "",
    ...noCache.flatMap((p) => [p, "  Cache-Control: no-cache", ""]),
  ].join("\n");
}

/** 언어 없는 랜딩 주소 → 기본 언어(en) 판으로. 루트(/)는 언어 고르기 페이지가 맡는다. */
export function redirectsFile(base = "/"): string {
  const b = normBase(base);
  const lines = ["# generated - landing paths without a language go to the default language (en)"];
  for (const r of ROUTES) {
    if (!r.slug) continue;
    const to = routePath(r.id, DEFAULT_LANG, base);
    lines.push(`${b}${r.slug}  ${to}  301`, `${b}${r.slug}/  ${to}  301`);
  }
  return lines.join("\n") + "\n";
}

export function allPagePaths(base = "/"): { id: RouteId; lang: Lang; path: string }[] {
  return ROUTES.flatMap((r) => LANGS.map((lang) => ({ id: r.id, lang, path: routePath(r.id, lang, base) })));
}

export function sitemapXml(siteUrl: string, base = "/"): string {
  const urls = ROUTES.flatMap((r) =>
    LANGS.map((lang) => {
      const alt = [
        ...LANGS.map((l) => `    <xhtml:link rel="alternate" hreflang="${l}" href="${esc(absUrl(siteUrl, routePath(r.id, l, base)))}"/>`),
        `    <xhtml:link rel="alternate" hreflang="x-default" href="${esc(absUrl(siteUrl, routePath(r.id, DEFAULT_LANG, base)))}"/>`,
      ];
      return [`  <url>`, `    <loc>${esc(absUrl(siteUrl, routePath(r.id, lang, base)))}</loc>`, ...alt, `  </url>`].join("\n");
    }),
  );
  return [
    `<?xml version="1.0" encoding="UTF-8"?>`,
    `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">`,
    ...urls,
    `</urlset>`,
    "",
  ].join("\n");
}

export function robotsTxt(siteUrl: string, base = "/"): string {
  return `User-agent: *\nAllow: /\n\nSitemap: ${absUrl(siteUrl, `${normBase(base)}sitemap.xml`)}\n`;
}

