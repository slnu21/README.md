function headLinks(siteUrl: string, base: string, id: RouteId, lang: Lang): string[] {
  const self = absUrl(siteUrl, routePath(id, lang, base));
  return [
    `<link rel="canonical" href="${esc(self)}" />`,
    ...LANGS.map((l) => `<link rel="alternate" hreflang="${l}" href="${esc(absUrl(siteUrl, routePath(id, l, base)))}" />`),
    `<link rel="alternate" hreflang="x-default" href="${esc(absUrl(siteUrl, routePath(id, DEFAULT_LANG, base)))}" />`,
  ];
}

function iconLinks(base: string, lang: Lang | null): string[] {
  const b = normBase(base);
  return [
    `<link rel="icon" type="image/svg+xml" href="${b}${ICONS.svg}" />`,
    `<link rel="icon" type="image/png" sizes="32x32" href="${b}${ICONS.png32}" />`,
    `<link rel="apple-touch-icon" href="${b}${ICONS.png256}" />`,
    ...(lang ? [`<link rel="manifest" href="${b}manifest-${lang}.webmanifest" />`] : []),
    `<meta name="theme-color" content="${THEME_COLOR}" />`,
  ];
}

const para = (s: string) => `<p>${esc(s)}</p>`;

/** 앱 아래의 설명 본문 — 보이는 정적 DOM(검색엔진·게시자 콘텐츠). 첫 화면에는 앱만 있고, 이것은 스크롤하면 나온다. */
export function introHtml(id: RouteId, lang: Lang, base = "/"): string {
  const c: LangCopy = COPY[lang];
  const r = c.routes[id];
  const other = LANGS.filter((l) => l !== lang);
  const pages = ROUTES.filter((x) => x.id !== id)
    .map((x) => `<li><a href="${routePath(x.id, lang, base)}">${esc(c.routes[x.id].nav)}</a></li>`)
    .join("");
  const syntax = c.syntax
    .map((s) => `<div class="wi-syn"><h3>${esc(s.name)}</h3><p>${esc(s.desc)}</p><pre><code>${esc(s.code)}</code></pre></div>`)
    .join("");
  return [
    `<a class="wi-hint" href="#about">${esc(c.hint)}</a>`,
    `<div id="web-intro" class="web-intro" lang="${lang}">`,
    `<article id="about" class="wi-body">`,
    `<header class="wi-head"><p class="wi-kicker">${esc(SITE_NAME)} · ${esc(BRAND_NAME)}</p><h1>${esc(r.h1)}</h1><p class="wi-desc">${esc(r.description)}</p></header>`,
    `<section class="wi-lead">${r.lead.map(para).join("")}</section>`,
    `<section><h2>${esc(c.howTitle)}</h2><ol>${c.how.map((s) => `<li>${esc(s)}</li>`).join("")}</ol></section>`,
    `<section><h2>${esc(c.syntaxTitle)}</h2><p>${esc(c.syntaxLead)}</p><div class="wi-syntax">${syntax}</div></section>`,
    `<section><h2>${esc(c.shareTitle)}</h2>${c.share.map(para).join("")}</section>`,
    `<section><h2>${esc(c.privacyTitle)}</h2>${c.privacy.map(para).join("")}</section>`,
    `<section class="wi-desktop"><h2>${esc(c.desktopTitle)}</h2>${c.desktop.map(para).join("")}<p><a class="wi-cta" href="${STORE_URL}" rel="noopener">${esc(c.desktopCta)}</a></p></section>`,
    `<nav class="wi-nav" aria-label="${esc(c.pagesTitle)}"><h2>${esc(c.pagesTitle)}</h2><ul>${pages}</ul></nav>`,
    `<nav class="wi-langs" aria-label="${esc(c.langTitle)}"><span>${esc(c.langTitle)}:</span> ${other
      .map((l) => `<a href="${routePath(id, l, base)}" hreflang="${l}" lang="${l}">${esc(COPY[l].langName)}</a>`)
      .join(" ")}</nav>`,
    `</article>`,
    `<footer class="wi-foot"><p>${esc(c.footer)} · <a class="wi-brand" href="${BRAND_URL}">${esc(BRAND_NAME)}</a> · © 2026 ${esc(AUTHOR)}</p></footer>`,
    `</div>`,
  ].join("\n");
}

function jsonLd(siteUrl: string, base: string, id: RouteId, lang: Lang): string {
  const r = COPY[lang].routes[id];
  // JSON 데이터 블록은 실행되지 않으므로 CSP(script-src 'self')에 걸리지 않는다. `<` 는 \u003c 로(블록 탈출 방지).
  const data = {
    "@context": "https://schema.org",
    "@type": "WebApplication",
    name: SITE_NAME,
    url: absUrl(siteUrl, routePath(id, lang, base)),
    description: r.description,
    inLanguage: lang,
    applicationCategory: "UtilitiesApplication",
    operatingSystem: "Any (web browser)",
    isAccessibleForFree: true,
    offers: { "@type": "Offer", price: "0", priceCurrency: "USD" },
    author: { "@type": "Person", name: AUTHOR },
    publisher: { "@type": "Organization", name: BRAND_NAME, url: BRAND_URL },
  };
  return `<script type="application/ld+json">${JSON.stringify(data).replace(/</g, "\\u003c")}</script>`;
}

export interface PageOptions {
  id: RouteId;
  lang: Lang;
  siteUrl: string;
  base?: string;
}

/** Vite 가 만든 index.html(스크립트·스타일 태그가 든 틀)을 한 페이지로. */
export function renderPage(template: string, o: PageOptions): string {
  const base = normBase(o.base);
  const c = COPY[o.lang];
  const r = c.routes[o.id];
  const route = routeById(o.id);
  const self = absUrl(o.siteUrl, routePath(o.id, o.lang, base));
  const head = [
    `<title>${esc(r.title)}</title>`,
    `<meta name="description" content="${esc(r.description)}" />`,
    ...headLinks(o.siteUrl, base, o.id, o.lang),
    `<meta property="og:type" content="website" />`,
    `<meta property="og:site_name" content="${esc(SITE_NAME)}" />`,
    `<meta property="og:title" content="${esc(r.title)}" />`,
    `<meta property="og:description" content="${esc(r.description)}" />`,
    `<meta property="og:url" content="${esc(self)}" />`,
    `<meta property="og:image" content="${esc(absUrl(o.siteUrl, `${base}${ICONS.png512}`))}" />`,
    `<meta property="og:locale" content="${c.ogLocale}" />`,
    `<meta name="twitter:card" content="summary" />`,
    ...iconLinks(base, o.lang),
    jsonLd(o.siteUrl, base, o.id, o.lang),
  ]
    .map((l) => `    ${l}`)
    .join("\n");
  let html = template;
  html = html.replace(/<html[^>]*>/i, `<html lang="${o.lang}" data-route="${route.id}" data-mode="${route.mode}" data-base="${base}">`);
  html = html.replace(/\s*<link rel="icon"[^>]*>/gi, "");
  html = html.replace(/<title>[\s\S]*?<\/title>/i, head.trimStart());
  html = html.replace(/(<div id="root"><\/div>)/i, `$1\n${introHtml(o.id, o.lang, base)}`);
  return html;
}

function plainPage(lang: Lang, title: string, body: string, base: string, extraHead: string[] = []): string {
  return [
    "<!doctype html>",
    `<html lang="${lang}">`,
    "  <head>",
    `    <meta charset="UTF-8" />`,
    `    <meta name="viewport" content="width=device-width, initial-scale=1" />`,
    `    <title>${esc(title)}</title>`,
    ...[...extraHead, ...iconLinks(base, null)].map((l) => `    ${l}`),
    // 인라인 스타일은 CSP 가 허용한다(style-src 'unsafe-inline'). 스크립트는 파일로만.
    `    <style>body{font:16px/1.6 system-ui,sans-serif;display:grid;place-items:center;min-height:100vh;margin:0;padding:0 16px;background:#fff;color:#1f2328;text-align:center}a{color:${THEME_COLOR};margin:0 .5em}h1{font-size:22px;margin:0 0 6px}@media (prefers-color-scheme:dark){body{background:#0f1115;color:#e6e6e6}a{color:#60a5fa}}</style>`,
    "  </head>",
    "  <body>",
    body,
    "  </body>",
    "</html>",
    "",
  ].join("\n");
}

