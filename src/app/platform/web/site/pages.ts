/** 루트의 언어 자동 이동 — CSP 가 인라인 스크립트를 막으므로 파일 하나로. 쿼리(?url=)·해시(#md=)는 그대로 넘긴다. */
export function langRedirectJs(base = "/"): string {
  const b = normBase(base);
  return `(function(){var l;try{l=localStorage.getItem(${JSON.stringify(LANG_PREF_KEY)})}catch(e){}
if(l!=="ko"&&l!=="en"){var n=(navigator.languages&&navigator.languages[0])||navigator.language||"";l=/^ko\\b/i.test(n)?"ko":"en"}
location.replace(${JSON.stringify(b)}+l+"/"+location.search+location.hash)})();
`;
}

