// ── 서비스 워커 ──
// 미리 받기 = 페이지·앱 자산 전부(오프라인에서 mermaid·수식까지 되게). 판이 바뀌어도 이름(해시)이 같은 자산은 옛 캐시에서
// 옮겨 담아 다시 받지 않는다. 페이지는 네트워크 먼저(새 배포가 바로 보이게) → 실패하면 캐시. 자산은 캐시 먼저(이름에 해시).
// skipWaiting 은 하지 않는다 — 열려 있는 탭이 쓰던 판의 지연 청크를 새 워커가 지우면 그 탭이 깨진다.
export function serviceWorkerJs(o: { version: string; precache: string[]; base?: string }): string {
  const b = normBase(o.base);
  return `// generated by app/platform/web/site/pages.ts serviceWorkerJs - do not edit
const CACHE = ${JSON.stringify(`readme-md-${o.version}`)};
const BASE = ${JSON.stringify(b)};
const PRECACHE = ${JSON.stringify(o.precache)};
const ASSETS = BASE + "assets/";

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await Promise.all(PRECACHE.map(async (path) => {
      try {
        if (path.startsWith(ASSETS)) {
          const old = await caches.match(path);
          if (old) return cache.put(path, old);
        }
        const res = await fetch(path, { cache: "no-cache" });
        if (res.ok && !res.redirected) await cache.put(path, res);
      } catch (e) {
        // 하나 못 받아도 설치는 계속 — 그 파일은 다음 방문에 네트워크로
      }
    }));
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((k) => k.startsWith("readme-md-") && k !== CACHE).map((k) => caches.delete(k)));
    await self.clients.claim();
  })());
});

function pageKey(url) {
  let p = url.pathname;
  if (p.endsWith("/index.html")) p = p.slice(0, -10);
  if (!p.endsWith("/") && !/\\.[a-z0-9]+$/i.test(p)) p += "/";
  return p;
}

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(BASE)) return;
  if (req.mode === "navigate") {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE);
      try {
        const res = await fetch(req);
        if (res.ok && PRECACHE.includes(pageKey(url))) cache.put(pageKey(url), res.clone());
        return res;
      } catch (e) {
        return (await cache.match(pageKey(url))) || (await cache.match(BASE + "404.html")) || Response.error();
      }
    })());
    return;
  }
  event.respondWith((async () => {
    const hit = await caches.match(url.pathname.startsWith(ASSETS) ? url.pathname : req);
    return hit || fetch(req);
  })());
});
`;
}

/** 텍스트 조각들로 판 이름 — 같은 산출물이면 같은 이름(CRC-32, 16진 8자). */
export function versionOf(parts: string[]): string {
  let crc = 0xffffffff;
  for (const s of parts) {
    for (let i = 0; i < s.length; i++) {
      let c = (crc ^ s.charCodeAt(i)) & 0xff;
      for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
      crc = (crc >>> 8) ^ c;
    }
  }
  return ((crc ^ 0xffffffff) >>> 0).toString(16).padStart(8, "0");
}

/** 미리 받을 경로 — 출력 파일 목록에서 배포 설정·검색엔진용 파일을 빼고, 페이지는 디렉터리 주소로. */
export function precacheList(files: string[], base = "/"): string[] {
  const b = normBase(base);
  const skip = /^(_headers|_redirects|sitemap\.xml|robots\.txt|sw\.js|vite\.svg|tauri\.svg)$/;
  const out = new Set<string>();
  for (const f of files) {
    const n = f.replace(/\\/g, "/").replace(/^\/+/, "");
    if (skip.test(n)) continue;
    if (n === "index.html") out.add(b);
    else if (n.endsWith("/index.html")) out.add(`${b}${n.slice(0, -"index.html".length)}`);
    else out.add(`${b}${n}`);
  }
  return [...out].sort();
}
